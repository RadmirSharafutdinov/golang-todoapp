package core_postgres_poll

import (
	"context"
	"fmt"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
	"github.com/jackc/pgx/v5/pgxpool"
)

type Pool interface {
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
	Exec(ctx context.Context, sql string, arguments ...any) (pgconn.CommandTag, error)
	Close()
	OppTimeout() time.Duration
}

type ConntectionPool struct {
	*pgxpool.Pool
	oppTimeout time.Duration
}

func NewConnectionPool(
	ctx context.Context,
	config Config,
) (*ConntectionPool, error) {
	connectionString := fmt.Sprintf(
		"postgres://%s:%s@%s:%s/%s?sslmode=disable",
		config.User,
		config.Password,
		config.Host,
		config.Port,
		config.Database,
	)
	pgxconfig, err := pgxpool.ParseConfig(connectionString)
	if err != nil {
		return nil, fmt.Errorf("parse pgxconfig: %w", err)
	}

	pool, err := pgxpool.NewWithConfig(ctx, pgxconfig)
	if err != nil {
		return nil, fmt.Errorf("create pgxconfig: %w", err)
	}

	return &ConntectionPool{
		Pool:       pool,
		oppTimeout: config.Timeout,
	}, nil
}
func (p *ConntectionPool) OppTimeout() time.Duration {
	return p.oppTimeout
}
